/**
 * Wrangler local dev reads secrets from `.dev.vars` (and `.env` when present).
 * Ensures JWT_SECRET and other worker env vars exist for `pnpm cf:dev`.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const devVarsPath = path.join(root, '.dev.vars')

const LOCAL_JWT_SECRET = 'local-dev-jwt-secret-change-me'

function parseEnvFile(filePath) {
  const out = {}
  if (!fs.existsSync(filePath)) return out
  for (const line of fs.readFileSync(filePath, 'utf8').split('\n')) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const eq = trimmed.indexOf('=')
    if (eq === -1) continue
    const key = trimmed.slice(0, eq).trim()
    let value = trimmed.slice(eq + 1).trim()
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }
    out[key] = value
  }
  return out
}

function main() {
  const merged = {
    ...parseEnvFile(path.join(root, '.env.example')),
    ...parseEnvFile(path.join(root, '.env')),
    ...parseEnvFile(path.join(root, '.env.local')),
    ...parseEnvFile(devVarsPath),
  }

  if (!merged.JWT_SECRET?.trim()) {
    merged.JWT_SECRET = LOCAL_JWT_SECRET
    console.warn(
      `[sync-dev-vars] JWT_SECRET missing — using local dev default. Copy .env.example → .env and set JWT_SECRET for production-like testing.`,
    )
  }

  merged.CF_DEV = merged.CF_DEV?.trim() || '1'
  merged.DEV_ACCOUNTS_URL = (merged.DEV_ACCOUNTS_URL?.trim() || 'http://localhost:8788').replace(/\/$/, '')
  merged.DEV_BSPLUS_URL = (merged.DEV_BSPLUS_URL?.trim() || 'http://localhost:8787').replace(/\/$/, '')
  merged.DEV_MAIL_URL = (merged.DEV_MAIL_URL?.trim() || 'http://localhost:8789').replace(/\/$/, '')
  merged.APP_URL = merged.APP_URL?.trim() || merged.DEV_ACCOUNTS_URL

  const lines = ['# Local worker secrets (auto-generated by scripts/sync-dev-vars.mjs)']
  const keys = [
    'JWT_SECRET',
    'APP_URL',
    'CF_DEV',
    'DEV_ACCOUNTS_URL',
    'DEV_BSPLUS_URL',
    'DEV_MAIL_URL',
    'SMTP2GO_API_KEY',
    'SMTP2GO_FROM_EMAIL',
    'DISCORD_CLIENT_ID',
    'DISCORD_CLIENT_SECRET',
    'DISCORD_REDIRECT_URI',
    'GOOGLE_OAUTH_CLIENT_ID',
    'GOOGLE_OAUTH_CLIENT_SECRET',
    'MICROSOFT_CALENDAR_CLIENT_ID',
    'MICROSOFT_CALENDAR_CLIENT_SECRET',
    'MICROSOFT_CALENDAR_REDIRECT_URI',
  ]

  for (const key of keys) {
    if (merged[key]?.trim()) {
      lines.push(`${key}=${merged[key]}`)
    }
  }

  for (const [key, value] of Object.entries(merged)) {
    if (keys.includes(key)) continue
    if (value?.trim()) lines.push(`${key}=${value}`)
  }

  fs.writeFileSync(devVarsPath, `${lines.join('\n')}\n`)
  console.log(`[sync-dev-vars] Wrote ${devVarsPath}`)
}

main()
