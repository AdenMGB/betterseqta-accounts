/**
 * Probes local BetterSEQTA services and writes resolved DEV_* URLs to `.env.local`.
 * Run before `cf:dev` / `worker:dev` so cross-service calls hit localhost, not production.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const envLocalPath = path.join(root, '.env.local')

const SERVICES = [
  { key: 'DEV_ACCOUNTS_URL', defaultPort: 8788, label: 'accounts' },
  { key: 'DEV_BSPLUS_URL', defaultPort: 8787, label: 'bsplus' },
  { key: 'DEV_MAIL_URL', defaultPort: 8789, label: 'mail' },
]

const DEV_FLAGS = [{ key: 'CF_DEV', value: '1' }]

function parseEnvFile(filePath) {
  const out = {}
  if (!fs.existsSync(filePath)) return out
  for (const line of fs.readFileSync(filePath, 'utf8').split('\n')) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const eq = trimmed.indexOf('=')
    if (eq === -1) continue
    const key = trimmed.slice(0, eq).trim()
    let value = trimmed.slice(eq + 1).trim()
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }
    out[key] = value
  }
  return out
}

function mergeEnvSources() {
  const merged = { ...parseEnvFile(path.join(root, '.env')), ...parseEnvFile(envLocalPath) }
  const devVarsPath = path.join(root, '.dev.vars')
  if (fs.existsSync(devVarsPath)) {
    Object.assign(merged, parseEnvFile(devVarsPath))
  }
  for (const svc of SERVICES) {
    if (process.env[svc.key]) merged[svc.key] = process.env[svc.key]
  }
  return merged
}

function defaultUrl(port) {
  return `http://localhost:${port}`
}

async function probe(url) {
  try {
    const controller = new AbortController()
    const timeout = setTimeout(() => controller.abort(), 2000)
    const res = await fetch(`${url.replace(/\/$/, '')}/api/health`, { signal: controller.signal })
    clearTimeout(timeout)
    return res.ok
  } catch {
    return false
  }
}

async function resolveServiceUrl(svc, existing) {
  const url = (existing[svc.key] || defaultUrl(svc.defaultPort)).replace(/\/$/, '')

  if (await probe(url)) {
    console.log(`[resolve-dev-services] ${svc.label}: ${url} (reachable)`)
    return url
  }

  console.warn(
    `[resolve-dev-services] ${svc.label}: ${url} not up yet — using default (start other services in parallel)`
  )
  return url
}

function writeEnvLocal(resolved) {
  const existing = parseEnvFile(envLocalPath)
  const lines = []
  const seen = new Set()

  if (fs.existsSync(envLocalPath)) {
    for (const line of fs.readFileSync(envLocalPath, 'utf8').split('\n')) {
      const trimmed = line.trim()
      const key = trimmed.split('=')[0]?.trim()
      if (key && resolved[key] !== undefined) {
        lines.push(`${key}=${resolved[key]}`)
        seen.add(key)
        continue
      }
      lines.push(line)
    }
  }

  for (const svc of SERVICES) {
    if (!seen.has(svc.key)) {
      if (lines.length && lines[lines.length - 1] !== '') lines.push('')
      if (!lines.some((l) => l.includes('Local dev service URLs'))) {
        lines.push('# Local dev service URLs (auto-generated by scripts/resolve-dev-services.mjs)')
      }
      lines.push(`${svc.key}=${resolved[svc.key]}`)
    }
  }

  for (const flag of DEV_FLAGS) {
    if (!seen.has(flag.key)) {
      lines.push(`${flag.key}=${flag.value}`)
    }
  }

  fs.writeFileSync(envLocalPath, lines.join('\n').replace(/\n+$/, '\n'))
  console.log(`[resolve-dev-services] Wrote ${envLocalPath}`)
}

async function main() {
  const isDev = process.env.NODE_ENV === 'development' || process.env.CF_DEV === '1'
  if (!isDev) {
    console.log('[resolve-dev-services] Skipping (set NODE_ENV=development or CF_DEV=1 to probe services)')
    return
  }

  const existing = mergeEnvSources()
  const resolved = { ...existing }

  for (const svc of SERVICES) {
    resolved[svc.key] = await resolveServiceUrl(svc, existing)
  }

  resolved.CF_DEV = '1'

  writeEnvLocal(resolved)
}

main().catch((err) => {
  console.error('[resolve-dev-services] Failed:', err)
  process.exit(1)
})
